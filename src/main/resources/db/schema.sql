-- 8. AI调用日志表（Observability）
-- ============================================================
DROP TABLE IF EXISTS ai_call_log;
CREATE TABLE ai_call_log (
    id            BIGINT       NOT NULL AUTO_INCREMENT COMMENT '日志ID',
    session_id    BIGINT       DEFAULT NULL COMMENT '会话ID',
    user_id       BIGINT       DEFAULT NULL COMMENT '用户ID',
    model         VARCHAR(50)  DEFAULT NULL COMMENT '使用的模型',
    prompt_tokens INT          DEFAULT 0 COMMENT '输入token数',
    completion_tokens INT      DEFAULT 0 COMMENT '输出token数',
    total_tokens  INT          DEFAULT 0 COMMENT '总token数',
    llm_duration  BIGINT       DEFAULT 0 COMMENT 'LLM调用耗时(ms)',
    tool_duration BIGINT       DEFAULT 0 COMMENT '工具调用总耗时(ms)',
    total_duration BIGINT      DEFAULT 0 COMMENT '总耗时(ms)',
    tool_names    VARCHAR(200) DEFAULT NULL COMMENT '调用的工具名(逗号分隔)',
    status        VARCHAR(20)  NOT NULL DEFAULT 'SUCCESS' COMMENT '状态：SUCCESS/ERROR',
    error_msg     TEXT         DEFAULT NULL COMMENT '错误信息',
    user_query    TEXT         DEFAULT NULL COMMENT '用户问题',
    create_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    KEY idx_session_id (session_id),
    KEY idx_user_id (user_id),
    KEY idx_create_time (create_time),
    KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI调用日志表';
