-- ============================================================
-- 5. AI聊天会话表
-- ============================================================
DROP TABLE IF EXISTS chat_session;
CREATE TABLE chat_session (
    id          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '会话ID',
    user_id     BIGINT       NOT NULL COMMENT '所属用户ID',
    title       VARCHAR(100) NOT NULL DEFAULT '新对话' COMMENT '会话标题',
    status      TINYINT      NOT NULL DEFAULT 0 COMMENT '状态：0-进行中，1-已结束',
    create_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后消息时间',
    deleted     TINYINT      NOT NULL DEFAULT 0 COMMENT '逻辑删除',
    PRIMARY KEY (id),
    KEY idx_user_id (user_id),
    KEY idx_update_time (update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI聊天会话表';

-- ============================================================
-- 6. AI聊天消息表
-- ============================================================
DROP TABLE IF EXISTS chat_message;
CREATE TABLE chat_message (
    id            BIGINT       NOT NULL AUTO_INCREMENT COMMENT '消息ID',
    session_id    BIGINT       NOT NULL COMMENT '所属会话ID',
    user_id       BIGINT       NOT NULL COMMENT '所属用户ID（冗余，方便查历史）',
    role          VARCHAR(20)  NOT NULL COMMENT '角色：user/assistant/system/tool',
    content       TEXT         COMMENT '消息内容',
    message_type  VARCHAR(20)  NOT NULL DEFAULT 'text' COMMENT '消息类型：text/tool_call/tool_result',
    tool_name     VARCHAR(50)  DEFAULT NULL COMMENT '调用的工具名（tool消息才有）',
    token_count   INT          DEFAULT 0 COMMENT '消耗token数',
    create_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (id),
    KEY idx_session_id (session_id),
    KEY idx_user_id (user_id),
    KEY idx_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI聊天消息表';

